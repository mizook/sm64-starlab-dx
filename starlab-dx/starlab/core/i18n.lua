    table.sort(english, function(a, b)
        return #a[1] > #b[1]
    end)

    function i18n.tr(text)
        local lang = string.lower(smlua_text_utils_get_language() or "English")
        if lang:find("spanish", 1, true) or lang:find("espa", 1, true) or lang == "es" then
            return text
        end
        for _, pair in ipairs(english) do
            -- Plain substring matching: format tokens and user profile names are not patterns.
            local startAt = 1
            while true do
                local a, b = text:find(pair[1], startAt, true)
                if not a then
                    break
                end
                text = text:sub(1, a - 1) .. pair[2] .. text:sub(b + 1)
                startAt = a + #pair[2]
            end
        end
        return text
    end

    function i18n.printText(text, x, y, scale)
        djui_hud_print_text(i18n.tr(text), x, y, scale)
    end

    function i18n.say(text)
        djui_chat_message_create("[StarLab] " .. i18n.tr(text))
    end
